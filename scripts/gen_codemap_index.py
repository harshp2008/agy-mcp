#!/usr/bin/env python3
"""Regenerate the mechanical module index inside ``doc/project/code-layout.md``.

Only the text between the two markers below is touched; all hand-written
prose around it is preserved byte for byte::

    <!-- BEGIN GENERATED -->
    ...
    <!-- END GENERATED -->

Usage::

    .venv/bin/python scripts/gen_codemap_index.py --write
    .venv/bin/python scripts/gen_codemap_index.py --check   # exit 1 if stale
"""

from __future__ import annotations

import argparse
import ast
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES_DIR = ROOT / "src" / "agy_mcp"
CODEMAP_PATH = ROOT / "doc" / "project" / "code-layout.md"

BEGIN_MARKER = "<!-- BEGIN GENERATED -->"
END_MARKER = "<!-- END GENERATED -->"


@dataclass(frozen=True)
class ModuleInfo:
    """One importable module and the public names it exposes."""

    name: str
    lines: int
    api: tuple[str, ...]


def _public(node: ast.AST) -> bool:
    return isinstance(
        node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
    ) and not node.name.startswith("_")


def _describe(node: ast.AST) -> str:
    """Render a top-level definition as ``name()`` or ``Class(method, ...)``."""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return f"`{node.name}()`"
    assert isinstance(node, ast.ClassDef)
    methods = [
        child.name
        for child in node.body
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
        and not child.name.startswith("_")
    ]
    if not methods:
        return f"`{node.name}`"
    rendered = ", ".join(f"`{m}`" for m in methods)
    return f"`{node.name}` ({rendered})"


def module_name(path: Path) -> str:
    """Return the dotted name of *path* relative to the package directory.

    The name keeps the ``.py`` suffix so top-level rows stay readable and the
    table is unchanged for a flat package, while a subpackage module is still
    unambiguous: ``audit.py``, but ``cleanup.store_io.py`` -- not ``store_io.py``,
    which would collide with a top-level module of the same name and hide which
    package it belongs to.
    """
    rel = path.relative_to(MODULES_DIR)
    return rel.as_posix().replace("/", ".")


def collect_modules() -> list[ModuleInfo]:
    """Return module metadata for the whole package tree, sorted by dotted name.

    The walk is recursive (``rglob``) so a subpackage added later cannot silently
    vanish from the index; before this change ``glob("*.py")`` indexed only the
    flat top level (audit A11/R6).
    """
    modules: list[ModuleInfo] = []
    for path in MODULES_DIR.rglob("*.py"):
        if "__pycache__" in path.parts:
            continue
        source = path.read_text(encoding="utf-8")
        name = module_name(path)
        tree = ast.parse(source, filename=name)
        api = tuple(_describe(node) for node in tree.body if _public(node))
        modules.append(
            ModuleInfo(name=name, lines=len(source.splitlines()), api=api)
        )
    return sorted(modules, key=lambda info: info.name)


def render_block() -> str:
    """Render the generated table (markers included) from the current source tree."""
    rows = [
        "<!-- Generated by scripts/gen_codemap_index.py; do not edit by hand. -->",
        "",
        "| Module | Lines | Public classes and functions |",
        "| --- | ---: | --- |",
    ]
    for info in collect_modules():
        api = "; ".join(info.api) if info.api else "_(no public definitions)_"
        rows.append(f"| `{info.name}` | {info.lines} | {api} |")
    body = "\n".join(rows)
    return f"{BEGIN_MARKER}\n{body}\n{END_MARKER}"


def replace_generated(text: str) -> str:
    """Replace the marker-delimited block in *text* with a freshly rendered one."""
    start = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError(
            f"CODEMAP.md is missing the {BEGIN_MARKER} / {END_MARKER} markers"
        )
    end += len(END_MARKER)
    return text[:start] + render_block() + text[end:]


def _check(text: str) -> int:
    try:
        expected = replace_generated(text)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if expected == text:
        print("CODEMAP.md generated section is fresh")
        return 0
    print(
        "CODEMAP.md generated section is stale; run "
        ".venv/bin/python scripts/gen_codemap_index.py --write",
        file=sys.stderr,
    )
    return 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="rewrite the generated block")
    group.add_argument("--check", action="store_true", help="exit 1 when the block is stale")
    group.add_argument("--stdout", action="store_true", help="print the generated block")
    args = parser.parse_args(argv)

    if args.stdout:
        print(render_block())
        return 0

    if not CODEMAP_PATH.is_file():
        print(f"error: missing {CODEMAP_PATH}", file=sys.stderr)
        return 2

    text = CODEMAP_PATH.read_text(encoding="utf-8")
    if args.write:
        try:
            CODEMAP_PATH.write_text(replace_generated(text), encoding="utf-8")
        except ValueError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        print(f"updated {CODEMAP_PATH.relative_to(ROOT)}")
        return 0
    return _check(text)


if __name__ == "__main__":
    raise SystemExit(main())
