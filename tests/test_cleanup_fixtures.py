def _cli_env() -> dict[str, str]:
    """Run the worktree's code, not an editable install from another checkout."""
    env = os.environ.copy()
    prefix = str(REPO_ROOT / "src") + os.pathsep + str(REPO_ROOT)
    existing = env.get("PYTHONPATH")
    env["PYTHONPATH"] = prefix + (os.pathsep + existing if existing else "")
    return env


def _run(*args: object, expect: int = 0) -> subprocess.CompletedProcess[str]:
    cmd = [sys.executable, "-m", "agy_mcp.cleanup_fixtures", *[str(a) for a in args]]
    proc = subprocess.run(
        cmd,
        cwd=REPO_ROOT,
        env=_cli_env(),
        capture_output=True,
        text=True,
        timeout=CLI_TIMEOUT_SECONDS,
    )
    assert proc.returncode == expect, (
        f"expected rc {expect}, got {proc.returncode}\n"
        f"cmd: {cmd}\nstdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )
    return proc


def _run_json(*args: object) -> dict:
    proc = _run("--json", *args)
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError as exc:  # pragma: no cover - failure detail
        raise AssertionError(f"--json did not print one JSON object: {exc}\n{proc.stdout}")


@pytest.fixture
def store() -> Path:
    root = Path(os.environ["HOME"]) / "cleanup-fixture-tests" / uuid.uuid4().hex
    (root / "jobs").mkdir(parents=True)
    yield root
    shutil.rmtree(root, ignore_errors=True)


def _old() -> datetime:
    return datetime.now(timezone.utc) - timedelta(days=3)


def _pytest_repo(n: int = 1) -> Path:
    """A repository path that is structurally under a pytest temp root."""
    return (
        Path(tempfile.gettempdir())
        / "pytest-of-fixture"
        / f"pytest-{n}"
        / "test_fixture0"
        / "repo"
    )


def _real_repo() -> Path:
    return Path(os.environ["HOME"]) / "Documents" / "real-project"


def _write_job(
    store: Path,
    *,
    state: str = "failed",
    repo: Path | None = None,
    updated_at: datetime | None = None,
    created_at: datetime | None = None,
    pid: int | None = None,
    conversation_id: str | None = None,
    extra: dict | None = None,
) -> str:
    job_id = str(uuid.uuid4())
    job_dir = store / "jobs" / job_id
    job_dir.mkdir(parents=True)
    now = datetime.now(timezone.utc)
    created = created_at or now
    updated = updated_at or created
    data = {
        "schema_version": 1,
        "job_id": job_id,
        "title": "Fixture Test",
        "repo_path": str(repo if repo is not None else _pytest_repo()),
        "branch": f"agy/fixture-test-{job_id[:8]}",
        "base_commit": "0" * 40,
        "head_commit": "",
        "state": state,
        "model": "gemini-3.8-flash-medium",
        "model_resolved": None,
        "max_minutes": 240,
        "verify": None,
        "verify_timeout_seconds": 900,
        "conversation_id": conversation_id,
        "pid": pid,
        "pgid": None,
        "start_time": None,
        "worktree_path": str(job_dir / "work"),
        "commit_msg_generation": 0,
        "review_reason": None,
        "source_dirty": False,
        "recovered": False,
        "created_at": created.isoformat(),
        "updated_at": updated.isoformat(),
    }
    if extra:
        data.update(extra)
    (job_dir / "job.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    return job_id


def _ids(result: dict, bucket: str) -> set[str]:
    return {entry["job_id"] for entry in result[bucket]}


def _entry(result: dict, bucket: str, job_id: str) -> dict:
    for entry in result[bucket]:
        if entry["job_id"] == job_id:
            return entry
    raise AssertionError(f"{job_id} not in {bucket}: {result[bucket]}")


def _tree_hash(root: Path) -> str:
    """Hash relative paths, file bytes and symlink targets without following links."""
    digest = hashlib.sha256()

    def walk(directory: str, prefix: str) -> None:
        with os.scandir(directory) as iterator:
            entries = sorted(iterator, key=lambda entry: entry.name)
        for entry in entries:
            rel = prefix + entry.name
            if entry.is_symlink():
                digest.update(b"L" + rel.encode() + b"\0" + os.readlink(entry.path).encode())
            elif entry.is_dir(follow_symlinks=False):
                digest.update(b"D" + rel.encode() + b"\0")
                walk(entry.path, rel + "/")
            elif entry.is_file(follow_symlinks=False):
                digest.update(b"F" + rel.encode() + b"\0")
                with open(entry.path, "rb") as handle:
                    digest.update(handle.read())

    walk(str(root), "")
    return digest.hexdigest()


