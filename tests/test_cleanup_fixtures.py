def test_dry_run_is_default_and_changes_nothing(store: Path) -> None:
    _write_job(store, state="failed", updated_at=_old())
    _write_job(store, state="done", repo=_real_repo(), updated_at=_old())
    before = _tree_hash(store)

    result = _run_json("--store", store)

    assert result["dry_run"] is True
    assert result["deleted_count"] == 0
    assert result["deleted_ids"] == []
    assert result["manifest"] is None
    assert result["candidates"], "dry run must list its candidates"
    assert _tree_hash(store) == before


def test_delete_removes_exactly_the_candidates_and_writes_a_manifest(store: Path) -> None:
    old = _old()
    first = _write_job(store, state="failed", updated_at=old)
    second = _write_job(store, state="cancelled", updated_at=old)
    kept = _write_job(store, state="done", repo=_real_repo(), updated_at=old)
    kept_before = _tree_hash(store / "jobs" / kept)

    dry = _run_json("--store", store)
    assert _ids(dry, "candidates") == {first, second}

    result = _run_json("--yes", "--store", store)

    assert result["dry_run"] is False
    assert result["deleted_count"] == 2
    assert set(result["deleted_ids"]) == {first, second}
    assert not (store / "jobs" / first).exists()
    assert not (store / "jobs" / second).exists()
    assert _tree_hash(store / "jobs" / kept) == kept_before

    manifest_path = Path(result["manifest"])
    assert manifest_path.is_file()
    assert manifest_path.parent == store / "jobs"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert set(manifest["removed_ids"]) == {first, second}
    assert all(isinstance(item, str) for item in manifest["removed_ids"])


def test_follow_up_edge_from_a_kept_row_protects_its_target(store: Path) -> None:
    target = _write_job(store, state="failed", updated_at=_old())
    _write_job(
        store,
        state="done",
        repo=_real_repo(),
        updated_at=_old(),
        extra={"follow_up_of": target},
    )

    dry = _run_json("--store", store)
    assert target not in _ids(dry, "candidates")
    assert target in _ids(dry, "kept")
    assert _entry(dry, "kept", target).get("reasons")

    result = _run_json("--yes", "--store", store)
    assert result["deleted_count"] == 0
    assert (store / "jobs" / target).is_dir()
