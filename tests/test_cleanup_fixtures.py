def test_store_outside_home_is_refused(tmp_path: Path) -> None:
    outside = tmp_path / "outside-store"
    (outside / "jobs").mkdir(parents=True)

    _run("--store", outside, "--json", expect=2)

    assert outside.is_dir()


def test_symlinked_store_root_is_refused(store: Path) -> None:
    link = Path(os.environ["HOME"]) / "cleanup-fixture-tests" / f"link-{uuid.uuid4().hex}"
    os.symlink(store, link, target_is_directory=True)
    try:
        _run("--store", link, "--json", expect=2)
    finally:
        link.unlink()


def test_symlinked_job_dir_is_not_followed(store: Path) -> None:
    candidate = _write_job(store, state="failed", updated_at=_old())
    target = store / "outside-target"
    target.mkdir()
    (target / "keep.txt").write_text("keep", encoding="utf-8")
    symlink_id = str(uuid.uuid4())
    os.symlink(target, store / "jobs" / symlink_id, target_is_directory=True)

    dry = _run_json("--store", store)
    assert candidate in _ids(dry, "candidates")
    assert symlink_id not in _ids(dry, "candidates")
    assert symlink_id in _ids(dry, "kept")

    result = _run_json("--yes", "--store", store)
    assert result["deleted_count"] == 1
    assert not (store / "jobs" / candidate).exists()
    assert (store / "jobs" / symlink_id).is_symlink()
    assert (target / "keep.txt").read_text(encoding="utf-8") == "keep"


def test_symlinked_file_inside_a_job_keeps_the_job(store: Path) -> None:
    job_id = _write_job(store, state="failed", updated_at=_old())
    outside_file = store / "outside.txt"
    outside_file.write_text("keep", encoding="utf-8")
    os.symlink(outside_file, store / "jobs" / job_id / "link.txt")

    dry = _run_json("--store", store)
    assert job_id not in _ids(dry, "candidates")
    assert job_id in _ids(dry, "kept")

    result = _run_json("--yes", "--store", store)
    assert result["deleted_count"] == 0
    assert (store / "jobs" / job_id).is_dir()
    assert (store / "jobs" / job_id / "link.txt").is_symlink()
    assert outside_file.read_text(encoding="utf-8") == "keep"


