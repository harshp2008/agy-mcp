def test_fixture_signature_rows_are_listed(store: Path) -> None:
    old = _old()
    failed = _write_job(store, state="failed", updated_at=old)
    done = _write_job(
        store,
        state="done",
        updated_at=old,
        conversation_id="11111111-1111-4111-8111-111111111111",
    )
    cancelled = _write_job(store, state="cancelled", updated_at=old)

    result = _run_json("--store", store)

    assert result["dry_run"] is True
    assert _ids(result, "candidates") == {failed, done, cancelled}
    assert result["candidate_count"] == 3
    assert result["kept_count"] == len(result["kept"])
    for entry in result["candidates"]:
        assert entry.get("reasons"), f"candidate {entry['job_id']} has no reason"


def test_real_looking_rows_are_never_candidates(store: Path) -> None:
    real = _real_repo()
    old = _old()
    done = _write_job(
        store,
        state="done",
        repo=real,
        updated_at=old,
        conversation_id="22222222-2222-4222-8222-222222222222",
    )
    failed = _write_job(store, state="failed", repo=real, updated_at=old)
    needs_review = _write_job(store, state="needs_review", repo=real, updated_at=old)
    needs_decision = _write_job(store, state="needs_decision", repo=real, updated_at=old)
    chained = _write_job(
        store,
        state="done",
        repo=real,
        updated_at=old,
        extra={"follow_up_of": failed, "parent_job_id": done},
    )

    result = _run_json("--store", store)

    expected = {done, failed, needs_review, needs_decision, chained}
    assert _ids(result, "candidates") == set()
    assert expected <= _ids(result, "kept")
    for job_id in expected:
        entry = _entry(result, "kept", job_id)
        assert entry.get("reasons"), f"kept row {job_id} has no reason"


def test_running_and_queued_rows_are_kept(store: Path) -> None:
    old = _old()
    running = _write_job(store, state="running", updated_at=old)
    queued = _write_job(store, state="queued", updated_at=old)

    result = _run_json("--store", store)

    assert _ids(result, "candidates") == set()
    assert {running, queued} <= _ids(result, "kept")


