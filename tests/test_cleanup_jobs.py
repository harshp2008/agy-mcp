def test_project_age_filtering_default_and_custom(store: Path) -> None:
    """Jobs older than threshold are eligible; fresher jobs are kept with reasons."""
    repo = Path(os.environ["HOME"]) / "age_test_proj"
    repo.mkdir(parents=True, exist_ok=True)

    old_job = _write_job(store, repo=repo, state="done", updated_at=_old_time(days=10))
    fresh_job = _write_job(store, repo=repo, state="done", updated_at=_recent_time(days=3))

    # Default 7 days threshold: old_job eligible, fresh_job kept
    res_default = _run_json("--store", store, "--project", repo, expect=0)
    assert old_job in _ids(res_default, "candidates")
    assert fresh_job in _ids(res_default, "kept")
    fresh_entry = next(e for e in res_default["kept"] if e["job_id"] == fresh_job)
    assert any("age" in r.lower() or "day" in r.lower() for r in fresh_entry["reasons"])

    # Custom --older-than-days 2.0: fresh_job (3 days old) is now eligible
    res_custom = _run_json(
        "--store",
        store,
        "--project",
        repo,
        "--older-than-days",
        "2.0",
        expect=0,
    )
    assert old_job in _ids(res_custom, "candidates")
    assert fresh_job in _ids(res_custom, "candidates")


