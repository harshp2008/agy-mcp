    res = _run_json("--store", store, "--project", sibling, expect=0)
    assert job_id not in _ids(res, "candidates")

    # Prefix sharing
    prefix = Path(os.environ["HOME"]) / "exact_project-2"
    res = _run_json("--store", store, "--project", prefix, expect=0)
