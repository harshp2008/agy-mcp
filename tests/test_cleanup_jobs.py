    sentinel_repo.write_text("KEEP_ME_REPO", encoding="utf-8")

    sibling_dir = tmp_path / "sibling_dir"
    sibling_dir.mkdir(parents=True, exist_ok=True)
    sentinel_sibling = sibling_dir / "sibling_sentinel.txt"
    sentinel_sibling.write_text("KEEP_ME_SIBLING", encoding="utf-8")

