    other_repo = tmp_path / "other_repo"
    other_job = _write_job(store, repo=other_repo, state="done", updated_at=_old_time())

    # Branch list before
    branches_before = subprocess.run(
        ["git", "-C", str(repo), "branch"],
        env=get_safe_git_env(repo.parent),
        capture_output=True,
        text=True,
        check=True,
    ).stdout

    _run("--store", store, "--project", repo, "--yes", expect=0)

    # Candidate deleted
    assert not (store / "jobs" / cand_id).exists()
    # Unrelated job intact
    assert (store / "jobs" / other_job).is_dir()
    # Sentinels intact
    assert sentinel_repo.read_text(encoding="utf-8") == "KEEP_ME_REPO"
    assert sentinel_sibling.read_text(encoding="utf-8") == "KEEP_ME_SIBLING"

    # Git branches intact
    branches_after = subprocess.run(
        ["git", "-C", str(repo), "branch"],
        env=get_safe_git_env(repo.parent),
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert branches_after == branches_before


