def test_job_mode_repeatable_partial_exit_1_and_all_ineligible_exit_2(store: Path) -> None:
    """--job exits 1 on partial deletion, 2 if all ineligible, 0 if all deleted."""
    eligible_1 = _write_job(store, state="done", updated_at=_recent_time(days=0.5))
    ineligible = _write_job(store, state="running", updated_at=_recent_time(days=0.5))

    # All ineligible -> exits 2
    proc_none = _run("--store", store, "--job", ineligible, "--yes", expect=2)
    assert (store / "jobs" / ineligible).is_dir()
    assert "reason" in proc_none.stdout.lower() or "kept" in proc_none.stdout.lower()

    # Partial: one eligible, one ineligible -> exits 1
