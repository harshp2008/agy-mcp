def test_before_delete_seam_skips_corrupted_row(store: Path) -> None:
    """before_delete seam re-validates candidates fail-closed when job.json is corrupt.

    Test A: corrupt candidate is processed first.
    Superseded by D91/D92 fail-closed pre-delete recheck:
    Originally (D89), a candidate whose job.json became corrupt right before deletion
    was skipped while remaining candidates proceeded. Under D91/D92, any corrupt
    record on disk not being deleted blocks deletion of all remaining candidates.
    When the corrupted candidate is processed FIRST, its corrupt record stops deletion
    of all remaining candidates.
    Invariants tested:
    - cand_normal is NOT deleted, stays on disk, and is in failed_ids.
    - cand_normal reason names the corrupt record of cand_corrupt.
    - cand_corrupt is also in failed_ids and stays on disk.
    - manifest status is partial.
    - planned_ids partition into deleted_ids and failed_ids in result and manifest.
    """
    from agy_mcp.cleanup_jobs import run_cleanup

    repo = Path(os.environ["HOME"]) / "corrupt_seam_proj_a"
    repo.mkdir(parents=True, exist_ok=True)

    cand_corrupt = "00000000-0000-4000-8000-000000000001"
    cand_normal = "00000000-0000-4000-8000-000000000002"

    _write_job(store, job_id=cand_corrupt, repo=repo, state="done", updated_at=_old_time())
    _write_job(store, job_id=cand_normal, repo=repo, state="done", updated_at=_old_time())

    def before_delete_cb(job_id: str) -> None:
        if job_id == cand_corrupt:
            jfile = store / "jobs" / cand_corrupt / "job.json"
            jfile.write_text("{NOT_VALID_JSON", encoding="utf-8")

    result = run_cleanup(
        store,
        project=repo,
        dry_run=False,
        before_delete=before_delete_cb,
    )

    # Test A: cand_corrupt is processed first:
    # cand_normal is NOT deleted, stays on disk
    assert (store / "jobs" / cand_normal).is_dir(), "cand_normal must stay on disk when blocked"
    assert cand_normal not in result["deleted_ids"], "cand_normal must not be deleted"
    assert cand_normal in result["failed_ids"], "cand_normal must be in failed_ids"

    # cand_corrupt is also in failed_ids, stays on disk
    assert (store / "jobs" / cand_corrupt).is_dir(), "cand_corrupt must stay on disk"
    assert cand_corrupt not in result["deleted_ids"], "cand_corrupt must not be deleted"
    assert cand_corrupt in result["failed_ids"], "cand_corrupt must be in failed_ids"

    # cand_normal reason names the corrupt record
    s_normal = next(
        (s for s in result.get("skipped", []) if s.get("job_id") == cand_normal), None
    )
    assert s_normal is not None, "cand_normal must be reported in skipped"
    reasons = s_normal.get("reasons", [])
    assert any(
        cand_corrupt in r and ("corrupt" in r.lower() or "unreadable" in r.lower())
        for r in reasons
    ), f"cand_normal reason must name corrupt cand_corrupt record: {reasons}"

    # manifest status partial, planned_ids == deleted + failed as sets
    assert result.get("manifest") is not None
    mdata = json.loads(Path(result["manifest"]).read_text(encoding="utf-8"))
    assert mdata["status"] == "partial"

    planned_set = {cand_corrupt, cand_normal}
    deleted_set = set(result["deleted_ids"])
    failed_set = set(result["failed_ids"])
    assert planned_set == deleted_set | failed_set, (
        "planned_ids must partition into deleted and failed"
    )
    assert not (deleted_set & failed_set), "deleted and failed sets must be disjoint"
    assert set(mdata["planned_ids"]) == planned_set
    assert set(mdata["removed_ids"]) == deleted_set
    assert set(mdata["failed_ids"]) == failed_set


