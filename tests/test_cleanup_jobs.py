def test_project_negative_matches_strict(store: Path) -> None:
    """--project strictly rejects sibling, prefix, parent, child, or case differences."""
    base = Path(os.environ["HOME"]) / "exact_project"
    base.mkdir(parents=True, exist_ok=True)
    job_id = _write_job(store, repo=base, state="done", updated_at=_old_time())

