def test_min_age_days_nan_is_refused(store: Path) -> None:
    """--min-age-days nan must be refused with exit 2 and never delete fresh rows (R7).

    On unhardened code, float('nan') < 0 is False so validation passes, but
    age_seconds < nan is also False so fresh rows become candidates and are deleted.
    """
    fresh_time = datetime.now(timezone.utc) - timedelta(minutes=10)
    fresh_job = _write_fixture_job(store, state="failed", updated_at=fresh_time)

    # Dry-run with --min-age-days nan must exit 2
    proc_dry = _run("--store", store, "--min-age-days", "nan", expect=2)
    assert "min-age-days" in (proc_dry.stderr + proc_dry.stdout).lower()

    # Opt-in deletion with --min-age-days nan must also exit 2 and NOT delete
    proc_del = _run("--yes", "--store", store, "--min-age-days", "nan", expect=2)
    assert "min-age-days" in (proc_del.stderr + proc_del.stdout).lower()
    assert (store / "jobs" / fresh_job).is_dir(), "fresh job must not be deleted by nan min-age"


def test_min_age_days_inf_is_refused(store: Path) -> None:
    """--min-age-days inf must be refused with exit 2 as invalid non-finite value."""
    proc = _run("--store", store, "--min-age-days", "inf", expect=2)
    assert "min-age-days" in (proc.stderr + proc.stdout).lower()


def test_huge_pid_is_kept_without_crashing(store: Path) -> None:
    """A huge PID (10**30) must be kept without OverflowError aborting the scan (R6).

    On unhardened code, os.kill(10**30, 0) raises OverflowError which escapes
    run_cleanup and causes main to exit 1 with 'Unexpected internal error'.
    """
    huge_pid = 10**30
    job_id = _write_fixture_job(store, state="failed", updated_at=_old_time(), pid=huge_pid)

    # Dry run scan must succeed with exit 0 and keep the row
    result = _run_json("--store", store, expect=0)
    assert job_id in _ids(result, "kept")
    assert job_id not in _ids(result, "candidates")

    # Deletion run must also exit 0 and preserve the directory
    del_result = _run_json("--yes", "--store", store, expect=0)
    assert del_result["deleted_count"] == 0
    assert (store / "jobs" / job_id).is_dir(), "job with huge pid must never be deleted"


def test_absurd_pid_is_kept(store: Path) -> None:
    """A PID exceeding valid kernel ranges (e.g. 10_000_000) must be kept, not treated as dead.

    Linux pid_max is at most 4,194,304. Values beyond valid PID limits are absurd
    and must be kept rather than treated as an exited process candidate.
    """
    absurd_pid = 10_000_000
    job_id = _write_fixture_job(store, state="failed", updated_at=_old_time(), pid=absurd_pid)

    result = _run_json("--store", store, expect=0)
    assert job_id in _ids(result, "kept")
    assert job_id not in _ids(result, "candidates")


def test_ancestor_symlink_above_store_is_refused() -> None:
    """A store accessed through an ancestor symlink must be refused with exit 2 (R9).

    On unhardened code, store_path.is_symlink() checks only the leaf path;
    symlinked ancestor directories are followed and rows inside deleted.
    """
    base_tmp = Path(os.environ["HOME"]) / "cleaner-hardening-symlink-tests"
    base_tmp.mkdir(parents=True, exist_ok=True)
    try:
        real_parent = base_tmp / f"real_{uuid.uuid4().hex}"
        real_parent.mkdir()
        real_store = real_parent / "store"
        (real_store / "jobs").mkdir(parents=True)

        symlink_parent = base_tmp / f"sym_{uuid.uuid4().hex}"
        os.symlink(real_parent, symlink_parent, target_is_directory=True)

        store_via_symlink = symlink_parent / "store"
        candidate_id = _write_fixture_job(real_store, state="failed", updated_at=_old_time())

        # Dry run through ancestor symlink must be refused with exit 2
        proc = _run("--store", store_via_symlink, expect=2)
        assert "symlink" in (proc.stderr + proc.stdout).lower()

        # Deletion must also refuse and leave the job untouched
        proc_del = _run("--yes", "--store", store_via_symlink, expect=2)
        assert "symlink" in (proc_del.stderr + proc_del.stdout).lower()
        assert (real_store / "jobs" / candidate_id).is_dir()
    finally:
        shutil.rmtree(base_tmp, ignore_errors=True)


def test_kept_job_missing_job_json_keeps_all_candidates(store: Path) -> None:
    """A kept UUID directory missing job.json must fail closed and keep all candidates (R8).

    On unhardened code, a UUID directory with missing job.json is skipped during
    edge scanning (not added to unverified_kept), so candidate jobs are deleted.
    """
    old = _old_time()
    candidate_id = _write_fixture_job(store, state="failed", updated_at=old)

    # Create a kept UUID directory with NO job.json
    corrupt_uuid = str(uuid.uuid4())
    corrupt_dir = store / "jobs" / corrupt_uuid
    corrupt_dir.mkdir(parents=True)
    # No job.json inside corrupt_dir

    # Dry run: candidate must be kept due to unverified edges
    dry = _run_json("--store", store, expect=0)
    assert candidate_id not in _ids(dry, "candidates"), (
        "candidate must be kept when kept job unreadable"
    )
    assert candidate_id in _ids(dry, "kept")
    assert dry["candidate_count"] == 0

    # Deletion: must not delete the candidate
    del_result = _run_json("--yes", "--store", store, expect=0)
    assert del_result["deleted_count"] == 0
    assert (store / "jobs" / candidate_id).is_dir(), "candidate must not be deleted"


def test_kept_job_corrupt_non_object_job_json_keeps_all_candidates(store: Path) -> None:
    """A kept UUID directory whose job.json is non-object (e.g. [1,2,3]) must fail closed."""
    old = _old_time()
    candidate_id = _write_fixture_job(store, state="failed", updated_at=old)

    # Create a kept UUID directory with non-object JSON
    corrupt_uuid = str(uuid.uuid4())
    corrupt_dir = store / "jobs" / corrupt_uuid
    corrupt_dir.mkdir(parents=True)
    (corrupt_dir / "job.json").write_text("[1, 2, 3]", encoding="utf-8")

    dry = _run_json("--store", store, expect=0)
    assert candidate_id not in _ids(dry, "candidates")
    assert candidate_id in _ids(dry, "kept")
    assert dry["candidate_count"] == 0

    del_result = _run_json("--yes", "--store", store, expect=0)
    assert del_result["deleted_count"] == 0
    assert (store / "jobs" / candidate_id).is_dir()


