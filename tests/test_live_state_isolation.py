"""FROZEN acceptance tests for Task A (tests can never touch the live store).

Committed before the implementation. Do not edit this file to make an
implementation pass: if a test here contradicts the task spec, stop and report
(needs_decision) with the test name and reason.

The tests never read, list or stat anything under the operator's real
``~/.local/state/agy-mcp``. They use the real path only as a string that the
guard must reject, and they assert on resolved paths / a sentinel HOME.
"""

import re
from pathlib import Path

import pytest

import agy_mcp.jobs as jobs_mod
from agy_mcp.manager import JobManager

TESTS_DIR = Path(__file__).resolve().parent
THIS_FILE = Path(__file__).resolve()

# A test may not hardcode, or re-derive at runtime, the operator's real state
# path. Path.home()/expanduser() are safe only inside tests/conftest.py (which
# captures the real path before redirecting HOME).
_FORBIDDEN_PATTERNS = (
    # Path.home() used to build a state-ish path on the same line.
    re.compile(r"Path\s*\.\s*home\s*\(\s*\)\s*/\s*[^\n]*(?:\.local|state|agy-mcp)"),
    # expanduser("~...") used to build a state-ish path.
    re.compile(r"expanduser\s*\(\s*['\"][^'\"]*~[^'\"]*['\"]\s*\)"),
    # A literal absolute/real state path.
    re.compile(r"""['"](?:~|/home/[^'"]+)/\.local/state/agy-mcp"""),
)


def test_default_state_dir_is_under_pytest_temp_root(
    isolated_state, tmp_path_factory: pytest.TempPathFactory
) -> None:
    """(a) With the autouse fixture active, the default state dir is temp-rooted."""
    resolved = jobs_mod.get_base_state_dir().resolve()
    temp_root = tmp_path_factory.getbasetemp().resolve()
    assert resolved == temp_root or temp_root in resolved.parents, (
        f"default state dir {resolved} is not under the pytest temp root {temp_root}"
    )
    # And it is not the operator's live path.
    assert resolved != isolated_state.real_live_state.resolve()


def test_canary_real_state_dir_is_rejected_at_resolution(isolated_state) -> None:
    """(b) Constructing/resolving with the real path raises immediately."""
    real = isolated_state.real_live_state
    with pytest.raises(RuntimeError, match="live agy-mcp state"):
        jobs_mod.get_base_state_dir(real)
    with pytest.raises(RuntimeError, match="live agy-mcp state"):
        JobManager(base_state_dir=real)


def test_sentinel_home_never_resolves_to_the_real_state_dir(
    isolated_state, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """(c) A test that swaps HOME to a sentinel still lands under that sentinel."""
    sentinel = (tmp_path / "sentinel-home").resolve()
    sentinel.mkdir()
    monkeypatch.setenv("HOME", str(sentinel))
    monkeypatch.delenv("XDG_STATE_HOME", raising=False)
    monkeypatch.delenv("AGY_MCP_STATE_DIR", raising=False)

    resolved = jobs_mod.get_base_state_dir().resolve()
    expected = sentinel / ".local" / "state" / "agy-mcp"
    assert resolved == expected, f"expected {expected}, got {resolved}"
    assert sentinel in resolved.parents
    assert resolved != isolated_state.real_live_state.resolve()

    # A write under the sentinel is allowed and creates nothing under the real
    # home; resolving the real path is still rejected by the guard.
    (resolved / "jobs").mkdir(parents=True, exist_ok=True)
    assert (sentinel / ".local" / "state" / "agy-mcp" / "jobs").is_dir()
    with pytest.raises(RuntimeError, match="live agy-mcp state"):
        jobs_mod.get_base_state_dir(isolated_state.real_live_state)


def test_tests_do_not_hardcode_the_real_state_path() -> None:
    """(d) Static tripwire: no test re-derives the operator's real state path."""
    offenders: list[str] = []
    for path in sorted(TESTS_DIR.rglob("*.py")):
        if "__pycache__" in path.parts or path.resolve() == THIS_FILE:
            continue
        if path.name == "conftest.py":
            # conftest captures the real path before redirecting HOME.
            continue
        text = path.read_text(encoding="utf-8")
        for pattern in _FORBIDDEN_PATTERNS:
            for match in pattern.finditer(text):
                line = text.count("\n", 0, match.start()) + 1
                offenders.append(
                    f"{path.relative_to(TESTS_DIR)}:{line}: {match.group(0)!r}"
                )
    assert not offenders, (
        "tests must not hardcode or re-derive the real state path; move the "
        "value into tests/conftest.py and use the isolated_state fixture:\n"
        + "\n".join(offenders)
    )
